-- 초기 스키마. H2(MODE=PostgreSQL)와 PostgreSQL 16 양쪽에서 그대로 실행된다.
-- 엔터티 매핑(@Entity)과 컬럼 이름·타입·nullable·unique·인덱스를 맞춘다. Hibernate는 ddl-auto=validate로만 검사한다.
-- 시각은 Instant -> timestamp(6) with time zone, 바이너리(PNG·PDF)는 bytea(H2에서는 VARBINARY 별칭)로 둔다.

create table anon_user (
    id            uuid                        not null,
    nickname      varchar(20)                 not null,
    token_hash    char(64)                    not null,
    recovery_hash char(64),
    sample        boolean                     not null,
    created_at    timestamp(6) with time zone not null,
    constraint pk_anon_user primary key (id),
    constraint uk_anon_user_token_hash unique (token_hash)
);

create table resume (
    id          uuid                        not null,
    owner_id    uuid                        not null,
    title       varchar(60)                 not null,
    target_role varchar(40)                 not null,
    sample      boolean                     not null,
    created_at  timestamp(6) with time zone not null,
    constraint pk_resume primary key (id),
    constraint fk_resume_owner foreign key (owner_id) references anon_user (id)
);
create index idx_resume_owner on resume (owner_id);

create table resume_version (
    id              uuid                        not null,
    resume_id       uuid                        not null,
    version_no      integer                     not null,
    status          varchar(10)                 not null,
    extracted_text  varchar                     not null,
    page_count      integer                     not null,
    preview_hash    varchar(64)                 not null,
    warnings        varchar(1000),
    unmatched_terms varchar(2000),
    name_candidate  varchar(100),
    created_at      timestamp(6) with time zone not null,
    published_at    timestamp(6) with time zone,
    constraint pk_resume_version primary key (id),
    constraint uk_resume_version_no unique (resume_id, version_no),
    constraint fk_version_resume foreign key (resume_id) references resume (id)
);
create index idx_version_resume on resume_version (resume_id);

create table draft_source (
    version_id uuid                        not null,
    pdf        bytea                       not null,
    expires_at timestamp(6) with time zone not null,
    constraint pk_draft_source primary key (version_id),
    constraint fk_draft_version foreign key (version_id) references resume_version (id)
);

create table page_image (
    version_id uuid    not null,
    page_no    integer not null,
    png        bytea   not null,
    width_px   integer not null,
    height_px  integer not null,
    constraint pk_page_image primary key (version_id, page_no),
    constraint fk_image_version foreign key (version_id) references resume_version (id)
);

create table mask_region (
    id         bigint generated by default as identity,
    version_id uuid             not null,
    page_no    integer          not null,
    type       varchar(10)      not null,
    x          double precision not null,
    y          double precision not null,
    w          double precision not null,
    h          double precision not null,
    constraint pk_mask_region primary key (id),
    constraint fk_region_version foreign key (version_id) references resume_version (id)
);
create index idx_region_version on mask_region (version_id);

create table mask_term (
    id         bigint generated by default as identity,
    version_id uuid        not null,
    term       varchar(30) not null,
    constraint pk_mask_term primary key (id),
    constraint fk_term_version foreign key (version_id) references resume_version (id)
);
create index idx_term_version on mask_term (version_id);

create table review (
    id          uuid                        not null,
    version_id  uuid                        not null,
    reviewer_id uuid                        not null,
    total_score smallint                    not null,
    summary     varchar(1000)               not null,
    sample      boolean                     not null,
    created_at  timestamp(6) with time zone not null,
    constraint pk_review primary key (id),
    constraint uk_review_version_reviewer unique (version_id, reviewer_id),
    constraint ck_review_score check (total_score between 1 and 5),
    constraint fk_review_version foreign key (version_id) references resume_version (id),
    constraint fk_review_reviewer foreign key (reviewer_id) references anon_user (id)
);
create index idx_review_version on review (version_id);

create table annotation (
    id        bigint generated by default as identity,
    review_id uuid             not null,
    seq       integer          not null,
    page_no   integer          not null,
    x         double precision not null,
    y         double precision not null,
    comment   varchar(500)     not null,
    constraint pk_annotation primary key (id),
    constraint uk_annotation_review_seq unique (review_id, seq),
    constraint ck_annotation_range check (x between 0 and 1 and y between 0 and 1 and page_no >= 1),
    constraint fk_annotation_review foreign key (review_id) references review (id)
);
create index idx_annotation_review on annotation (review_id);
